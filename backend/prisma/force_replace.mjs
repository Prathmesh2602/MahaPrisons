async function forceUpdate() {
  const blocks = await prisma.contentBlock.findMany();
  for (const b of blocks) {
    let str = JSON.stringify(b.content);
    if (isCorrupted(str)) {
      let fixed = str;
      for (const [corrupted, replacement] of Object.entries(replacements)) {
        fixed = fixed.split(corrupted).join(replacement);
      }
      if (fixed !== str) {
        await prisma.contentBlock.update({ where: { id: b.id }, data: { content: JSON.parse(fixed) } });
        console.log(`Force fixed ContentBlock: ${b.id}`);
      }
    }
  }

  const settings = await prisma.siteSetting.findMany();
  for (const s of settings) {
    let str = JSON.stringify(s.value);
    if (isCorrupted(str)) {
      let fixed = str;
      for (const [corrupted, replacement] of Object.entries(replacements)) {
        fixed = fixed.split(corrupted).join(replacement);
      }
      if (fixed !== str) {
        await prisma.siteSetting.update({ where: { id: s.id }, data: { value: JSON.parse(fixed) } });
        console.log(`Force fixed SiteSetting: ${s.id}`);
      }
    }
  }

  console.log('\n--- VERIFICATION ---');
  let cCb = 0;
  for (const b of await prisma.contentBlock.findMany()) if (isCorrupted(JSON.stringify(b.content))) {
    cCb++;
    console.log(`Still corrupted CB: ${b.id}`);
  }
  let cSs = 0;
  for (const s of await prisma.siteSetting.findMany()) if (isCorrupted(JSON.stringify(s.value))) {
    cSs++;
    console.log(`Still corrupted SS: ${s.id}`);
  }
  console.log(`Remaining Corrupted ContentBlocks: ${cCb}`);
  console.log(`Remaining Corrupted SiteSettings: ${cSs}`);

  prisma.$disconnect();
}
forceUpdate();
